#!/bin/bash
# Hardware/firmware/driver inventory for the ROG Zephyrus G16 (GU605MI), as Markdown.
# - Reads only sysfs/procfs values the kernel already caches. It deliberately does
#   NOT run lspci: config-space reads runtime-resume a sleeping NVIDIA GPU.
# - Prints no serial numbers, MAC addresses, UUIDs, hostnames or user names.
# usage: sudo tools/inventory.sh > docs/hardware.md   (root only for ACPI/debugfs bits)
set -u
r() { cat "$1" 2>/dev/null | tr -d '\n'; }
echo "# Hardware inventory"
echo
echo "_Generated by \`tools/inventory.sh\` on $(date +%F). Kernel $(uname -r)._"
echo
echo "## Platform"
echo
D=/sys/class/dmi/id
echo "| Item | Value |"
echo "|---|---|"
echo "| Vendor | $(r $D/sys_vendor) |"
echo "| Product | $(r $D/product_name) ($(r $D/product_family)) |"
echo "| Board | $(r $D/board_name) |"
echo "| BIOS | $(r $D/bios_vendor) $(r $D/bios_version), $(r $D/bios_date) |"
echo "| CPU | $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ //') ($(nproc) threads) |"
echo "| RAM | $(awk '/MemTotal/{printf "%.1f GiB", $2/1048576}' /proc/meminfo) |"
. /etc/os-release 2>/dev/null; echo "| OS | ${PRETTY_NAME:-?} |"
echo "| Kernel | $(uname -r) |"
[ -r /proc/driver/nvidia/version ] && echo "| NVIDIA driver | $(head -1 /proc/driver/nvidia/version | grep -oE '[0-9]{3}\.[0-9]+\.[0-9]+' | head -1) ($(grep -q 'Open Kernel' /proc/driver/nvidia/version && echo open || echo proprietary) kernel modules) |"
echo "| Sleep states | $(r /sys/power/state); mem_sleep: $(r /sys/power/mem_sleep); disk: $(r /sys/power/disk) |"
echo
echo "## PCI devices"
echo
echo "From sysfs (no config-space access). ACPI path = the firmware object for the device."
echo
echo "| Address | Class | ID | Driver | ACPI path | Runtime PM | D3cold allowed |"
echo "|---|---|---|---|---|---|---|"
for d in /sys/bus/pci/devices/*; do
    a=${d##*/}
    drv=$(basename "$(readlink "$d/driver" 2>/dev/null)" 2>/dev/null); [ -n "$drv" ] || drv="-"
    echo "| $a | $(r $d/class) | $(r $d/vendor | sed 's/0x//'):$(r $d/device | sed 's/0x//') | $drv | $(r $d/firmware_node/path) | $(r $d/power/control)/$(r $d/power/runtime_status) | $(r $d/d3cold_allowed) |"
done
echo
echo "## USB devices"
echo
echo "| Port | ID | Product | Driver(s) | Autosuspend | Wakeup |"
echo "|---|---|---|---|---|---|"
for u in /sys/bus/usb/devices/*; do
    [ -f "$u/idVendor" ] || continue
    case ${u##*/} in usb*) continue ;; esac
    drvs=$(for i in "$u":*; do basename "$(readlink "$i/driver" 2>/dev/null)" 2>/dev/null; done | sort -u | tr '\n' ' ')
    echo "| ${u##*/} | $(r $u/idVendor):$(r $u/idProduct) | $(r $u/manufacturer) $(r $u/product) | ${drvs:--} | $(r $u/power/control) | $(r $u/power/wakeup) |"
done
echo
echo "## Displays"
echo
echo "Connector state is the cached 'enabled' flag: reading 'status' makes the driver"
echo "probe the port, which wakes a sleeping NVIDIA GPU."
echo
echo "| Connector | Enabled | GPU (PCI) |"
echo "|---|---|---|"
for c in /sys/class/drm/card*-*; do
    [ -f "$c/enabled" ] || continue
    echo "| ${c##*/} | $(r $c/enabled) | $(basename "$(readlink -f "$c/device/device")") |"
done
echo
echo "## Audio"
echo
# Skip the NVIDIA HDMI audio function: reading its codec info wakes the GPU.
for f in /proc/asound/card*/codec#*; do
    [ -f "$f" ] || continue
    c=$(dirname "$f")
    case "$(r $c/id)" in *NVidia*|*NVIDIA*) echo "- ${c##*/}: NVIDIA HDMI/DP audio (not queried, it would wake the GPU)"; continue ;; esac
    echo "- ${c##*/} $(basename "$f"): $(grep -m1 '^Codec:' "$f" | cut -d: -f2- | sed 's/^ //')"
done | sort -u
for d in /sys/bus/spi/devices/* /sys/bus/i2c/devices/*; do
    n=$(r $d/modalias); case "$n" in *CSC*|*cs35*|*CS35*) echo "- amplifier: ${d##*/} ($n), driver $(basename "$(readlink "$d/driver" 2>/dev/null)")";; esac
done
echo
echo "## Storage, wireless, battery"
echo
for n in /sys/class/nvme/nvme*; do [ -d "$n" ] && echo "- NVMe: $(r $n/model | sed 's/ *$//'), firmware $(r $n/firmware_rev | sed 's/ *$//'), behind $(basename "$(readlink -f "$n/device/..")")"; done
w=$(ls /sys/class/net 2>/dev/null | grep -m1 '^wl'); [ -n "$w" ] && echo "- Wi-Fi: driver $(basename "$(readlink /sys/class/net/$w/device/driver)"), PCI $(r /sys/class/net/$w/device/vendor):$(r /sys/class/net/$w/device/device)"
B=/sys/class/power_supply/BAT1
[ -d $B ] && echo "- Battery: $(r $B/manufacturer) $(r $B/model_name), design $(awk '{printf "%.1f Wh", $1*'"$(r $B/voltage_min_design)"'/1e12}' $B/charge_full_design 2>/dev/null), now full $(awk '{printf "%.1f Wh", $1*'"$(r $B/voltage_min_design)"'/1e12}' $B/charge_full 2>/dev/null), cycles $(r $B/cycle_count)"
echo
echo "## Firmware loaded by drivers (this boot)"
echo
journalctl -k -b --no-pager -o cat 2>/dev/null | grep -oE '(i915|xe) [0-9a-f:.]+: \[drm\] (GT[0-9]: )?(GuC|HuC|DMC|GSC)[^,]*(firmware|version)[^,]*' | sed -E 's/^(i915|xe) [0-9a-f:.]+: \[drm\] //' | sort -u | sed 's/^/- /'
journalctl -k -b --no-pager -o cat 2>/dev/null | grep -oE 'iwlwifi [0-9a-f:.]+: loaded firmware version [^ ]+' | sort -u | sed -E 's/iwlwifi [0-9a-f:.]+: /- Wi-Fi /'
journalctl -k -b --no-pager -o cat 2>/dev/null | grep -oE 'Bluetooth: hci0: (Found device firmware|Firmware Version)[^$]*' | sort -u | sed 's/^/- /'
journalctl -k -b --no-pager -o cat 2>/dev/null | grep -oE 'DSP1: Firmware: [^$]*' | sort -u | sed 's/^/- speaker amps /'
if [ -r /sys/kernel/debug/pmc_core/substate_residencies ]; then
    echo
    echo "## Low-power idle (S0ix) substates"
    echo
    echo '```'
    cat /sys/kernel/debug/pmc_core/substate_residencies
    echo '```'
fi
